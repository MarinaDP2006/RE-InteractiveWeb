CREATE DATABASE IF NOT EXISTS umbrella_completa
  CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;
USE umbrella_completa;

SET NAMES utf8mb4 COLLATE utf8mb4_general_ci;
SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS sesiones, miembros, destacados, portada, relaciones,
  personaje_afiliaciones, ficha_etiquetas, ficha_curiosidades, ficha_cuerpo,
  juegos, peliculas, personajes, criaturas, virus, organizaciones, ubicaciones, cronologia,
  fichas, secciones;

SET FOREIGN_KEY_CHECKS = 1;

-- ------------------------------------------------------------
-- 1) CONFIGURACIÓN DE LA WIKI
-- ------------------------------------------------------------

-- Secciones del menú de la wiki
CREATE TABLE secciones (
  id           VARCHAR(30)  PRIMARY KEY,
  titulo       VARCHAR(60)  NOT NULL,
  descripcion  VARCHAR(255) NOT NULL,
  visible      BOOLEAN      NOT NULL DEFAULT TRUE,
  orden        SMALLINT     NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- Textos de la portada (una sola fila)
CREATE TABLE portada (
  id     TINYINT      PRIMARY KEY,
  titulo VARCHAR(60)  NOT NULL,
  lema   VARCHAR(120) NOT NULL,
  intro  TEXT         NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- ------------------------------------------------------------
-- 2) FICHAS
-- Generalización / especialización: "fichas" guarda lo común a
-- todas las secciones y cada sección tiene su tabla con sus
-- columnas propias, unida 1:1 por el mismo id.
-- Los id son únicos en toda la wiki (leon, t-virus, re2...).
-- ------------------------------------------------------------

CREATE TABLE fichas (
  id       VARCHAR(60)  PRIMARY KEY,
  seccion  VARCHAR(30)  NOT NULL,
  titulo   VARCHAR(120) NOT NULL,
  resumen  VARCHAR(400),
  imagen   VARCHAR(200),
  color    CHAR(7),
  orden    INT          NOT NULL DEFAULT 0,
  oculto   BOOLEAN      NOT NULL DEFAULT FALSE,   -- spoilers: solo para miembros
  CONSTRAINT fk_fichas_seccion FOREIGN KEY (seccion) REFERENCES secciones(id),
  INDEX idx_fichas_seccion_orden (seccion, orden)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE juegos (
  id             VARCHAR(60) PRIMARY KEY,
  subtitulo      VARCHAR(150),
  tipo           VARCHAR(60),
  canon          BOOLEAN NOT NULL DEFAULT TRUE,
  anio           SMALLINT,                 -- año de lanzamiento
  lanzamiento    VARCHAR(150),
  plataformas    VARCHAR(150),
  ambientacion   VARCHAR(120),
  anio_historia  DECIMAL(6,1),             -- cuándo ocurre (para ordenar por historia)
  lugar          VARCHAR(150),
  video          VARCHAR(20),              -- id de YouTube del tráiler
  CONSTRAINT fk_juegos_ficha FOREIGN KEY (id) REFERENCES fichas(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE peliculas (
  id             VARCHAR(60) PRIMARY KEY,
  tipo           VARCHAR(60),
  canon          BOOLEAN NOT NULL DEFAULT TRUE,
  anio           SMALLINT,
  director       VARCHAR(100),
  duracion       VARCHAR(40),
  ambientacion   VARCHAR(80),
  anio_historia  DECIMAL(6,1),
  video          VARCHAR(20),
  CONSTRAINT fk_peliculas_ficha FOREIGN KEY (id) REFERENCES fichas(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE personajes (
  id                 VARCHAR(60) PRIMARY KEY,
  alias              VARCHAR(100),
  nacimiento         VARCHAR(40),
  primera_aparicion  VARCHAR(60),
  estado             VARCHAR(60),
  rol                VARCHAR(60),
  cuerpo_imagen      VARCHAR(200),
  CONSTRAINT fk_personajes_ficha FOREIGN KEY (id) REFERENCES fichas(id) ON DELETE CASCADE,
  CONSTRAINT fk_personajes_primera FOREIGN KEY (primera_aparicion) REFERENCES fichas(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE criaturas (
  id                 VARCHAR(60) PRIMARY KEY,
  tipo               VARCHAR(60),
  origen             VARCHAR(30),
  primera_aparicion  VARCHAR(60),
  peligrosidad       TINYINT CHECK (peligrosidad BETWEEN 1 AND 5),
  debilidad          VARCHAR(120),
  CONSTRAINT fk_criaturas_ficha FOREIGN KEY (id) REFERENCES fichas(id) ON DELETE CASCADE,
  CONSTRAINT fk_criaturas_primera FOREIGN KEY (primera_aparicion) REFERENCES fichas(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE virus (
  id                 VARCHAR(60) PRIMARY KEY,
  tipo               VARCHAR(60),
  creador            VARCHAR(100),
  anio               SMALLINT,
  primera_aparicion  VARCHAR(60),
  efectos            VARCHAR(200),
  CONSTRAINT fk_virus_ficha FOREIGN KEY (id) REFERENCES fichas(id) ON DELETE CASCADE,
  CONSTRAINT fk_virus_primera FOREIGN KEY (primera_aparicion) REFERENCES fichas(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE organizaciones (
  id          VARCHAR(60) PRIMARY KEY,
  tipo        VARCHAR(80),
  fundacion   VARCHAR(30),
  disolucion  VARCHAR(30),
  lema        VARCHAR(100),
  CONSTRAINT fk_organizaciones_ficha FOREIGN KEY (id) REFERENCES fichas(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE ubicaciones (
  id          VARCHAR(60) PRIMARY KEY,
  tipo        VARCHAR(60),
  pais        VARCHAR(60),
  region      VARCHAR(100),
  mapa        ENUM('mundo','raccoon') NOT NULL DEFAULT 'mundo',
  lat         DECIMAL(9,6),             -- mapa del mundo
  lng         DECIMAL(9,6),
  aproximada  BOOLEAN NOT NULL DEFAULT FALSE,
  anio        VARCHAR(30),
  estado      VARCHAR(80),
  x           SMALLINT,                 -- mapa de Raccoon City (píxeles)
  y           SMALLINT,
  CONSTRAINT fk_ubicaciones_ficha FOREIGN KEY (id) REFERENCES fichas(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE cronologia (
  id     VARCHAR(60) PRIMARY KEY,
  anio   SMALLINT NOT NULL,
  fecha  VARCHAR(80),
  era    VARCHAR(40),
  tipo   ENUM('hito','juego','pelicula') NOT NULL DEFAULT 'hito',
  CONSTRAINT fk_cronologia_ficha FOREIGN KEY (id) REFERENCES fichas(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- ------------------------------------------------------------
-- 3) LISTAS DE CADA FICHA (1:N), en orden con "posicion"
-- ------------------------------------------------------------

-- Texto largo de la ficha: títulos de apartado y párrafos
CREATE TABLE ficha_cuerpo (
  ficha_id  VARCHAR(60) NOT NULL,
  posicion  SMALLINT    NOT NULL,
  tipo      ENUM('titulo','parrafo') NOT NULL DEFAULT 'parrafo',
  texto     TEXT        NOT NULL,
  PRIMARY KEY (ficha_id, posicion),
  CONSTRAINT fk_cuerpo_ficha FOREIGN KEY (ficha_id) REFERENCES fichas(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE ficha_curiosidades (
  ficha_id  VARCHAR(60) NOT NULL,
  posicion  SMALLINT    NOT NULL,
  texto     TEXT        NOT NULL,
  PRIMARY KEY (ficha_id, posicion),
  CONSTRAINT fk_curiosidades_ficha FOREIGN KEY (ficha_id) REFERENCES fichas(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE ficha_etiquetas (
  ficha_id  VARCHAR(60) NOT NULL,
  posicion  SMALLINT    NOT NULL,
  etiqueta  VARCHAR(60) NOT NULL,
  PRIMARY KEY (ficha_id, posicion),
  INDEX idx_etiqueta (etiqueta),
  CONSTRAINT fk_etiquetas_ficha FOREIGN KEY (ficha_id) REFERENCES fichas(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE personaje_afiliaciones (
  personaje_id  VARCHAR(60)  NOT NULL,
  posicion      SMALLINT     NOT NULL,
  afiliacion    VARCHAR(120) NOT NULL,
  PRIMARY KEY (personaje_id, posicion),
  CONSTRAINT fk_afiliaciones_personaje FOREIGN KEY (personaje_id) REFERENCES personajes(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- ------------------------------------------------------------
-- 4) RELACIONES ENTRE FICHAS (N:M)
-- Una sola tabla para todos los enlaces: protagonistas de un juego,
-- juegos en los que aparece un personaje, miembros de una organización...
--   origen_id  -> ficha que tiene la lista
--   tipo       -> nombre de la lista
--   destino_id -> ficha enlazada
-- ------------------------------------------------------------

CREATE TABLE relaciones (
  origen_id   VARCHAR(60) NOT NULL,
  tipo        ENUM('protagonistas','antagonistas','amenazas','ubicaciones','virus',
                   'apariciones','peliculas','derivados','miembros','juegos','relacionados') NOT NULL,
  destino_id  VARCHAR(60) NOT NULL,
  posicion    SMALLINT    NOT NULL,
  PRIMARY KEY (origen_id, tipo, destino_id),
  INDEX idx_relaciones_destino (destino_id),
  CONSTRAINT fk_relaciones_origen FOREIGN KEY (origen_id) REFERENCES fichas(id) ON DELETE CASCADE,
  CONSTRAINT fk_relaciones_destino FOREIGN KEY (destino_id) REFERENCES fichas(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- Fichas destacadas en la portada
CREATE TABLE destacados (
  posicion  TINYINT     PRIMARY KEY,
  ficha_id  VARCHAR(60) NOT NULL,
  CONSTRAINT fk_destacados_ficha FOREIGN KEY (ficha_id) REFERENCES fichas(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- ------------------------------------------------------------
-- 5) MIEMBROS Y SESIONES (antes en Supabase/PostgreSQL)
-- Acceso con Google: google_sub es el identificador de la cuenta.
-- De la sesión solo se guarda el hash del token, nunca el token.
-- ------------------------------------------------------------

CREATE TABLE miembros (
  google_sub     VARCHAR(255) PRIMARY KEY,
  correo         VARCHAR(255) NOT NULL,
  nombre         VARCHAR(120) NOT NULL,
  foto           VARCHAR(500) NOT NULL DEFAULT '',
  alta           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ultimo_acceso  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE sesiones (
  token_hash  VARCHAR(64)  PRIMARY KEY,   -- SHA-256 en Base64 (43 caracteres)
  google_sub  VARCHAR(255) NOT NULL,
  expira      TIMESTAMP    NOT NULL,
  INDEX idx_sesiones_expira (expira),
  INDEX idx_sesiones_miembro (google_sub),
  CONSTRAINT fk_sesiones_miembro FOREIGN KEY (google_sub) REFERENCES miembros(google_sub) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

